// Helper: Pick random item from array
function getRandom(arr) {
    return arr[Math.floor(Math.random() * arr.length)];
}

// Generate shop card items (count: number of items)
export function generateShopCards(count = 2) {
    const items = [];
    for (let i = 0; i < count; i++) {
        const rand = Math.random();
        if (rand < 0.70) {
            // Joker (70%)
            const joker = getRandom(SHOP_JOKERS);
            items.push({
                slotId: `shop-joker-${Date.now()}-${i}`,
                type: 'joker',
                id: joker.id,
                title: joker.title,
                rarity: joker.rarity,
                price: joker.price,
                description: joker.description
            });
        } else if (rand < 0.85) {
            // Tarot (15%)
            const tarot = getRandom(SHOP_TAROTS);
            items.push({
                slotId: `shop-tarot-${Date.now()}-${i}`,
                type: 'tarot',
                id: tarot.id,
                title: tarot.title,
                rarity: tarot.rarity,
                price: tarot.price,
                description: tarot.description
            });
        } else if (rand < 0.95) {
            // Planet (10%)
            const planet = getRandom(SHOP_PLANETS);
            items.push({
                slotId: `shop-planet-${Date.now()}-${i}`,
                type: 'planet',
                id: planet.id,
                title: planet.title,
                rarity: planet.rarity,
                price: planet.price,
                description: planet.description
            });
        } else {
            // Playing card (5%)
            const suits = ['Hearts', 'Spades', 'Diamonds', 'Clubs'];
            const ranks = ['A', 'K', 'Q', 'J', '10', '9', '8', '7'];
            const suit = getRandom(suits);
            const rank = getRandom(ranks);
            items.push({
                slotId: `shop-card-${Date.now()}-${i}`,
                type: 'playingCard',
                rank,
                suit,
                title: `${rank} of ${suit}`,
                rarity: 'Playing Card',
                price: 3,
                description: `Standard playing card (${rank} of ${suit}) to add to deck`
            });
        }
    }
    return items;
}

// Get Voucher for current Ante
export function getAnteVoucher(ante = 1) {
    const vouchers = ['Wasteful', 'Grabber', 'Overstock', 'ClearanceSale', 'TarotMerchant', 'PlanetMerchant', 'RerollSurplus', 'SeedMoney'];
    const idx = (ante - 1) % vouchers.length;
    const vId = vouchers[idx];
    return SHOP_VOUCHERS.find(v => v.id === vId) || SHOP_VOUCHERS[0];
}

// Generate 2 booster packs
export function generateBoosterPacks() {
    const pack1 = BOOSTER_PACKS[0]; // Standard Pack 1
    const pack2 = BOOSTER_PACKS[1]; // Standard Pack 2
    return [
        { ...pack1, slotId: 'booster-0' },
        { ...pack2, slotId: 'booster-1' }
    ];
}

// Universal card lookup function for tooltips
export function getCardInfo(id, type = 'joker') {
    if (!id) return { title: 'Card', description: '', rarity: 'Common' };

    if (type === 'joker') {
        const found = SHOP_JOKERS.find(j => j.id === id);
        if (found) return found;
        return {
            id,
            title: id.replace(/([A-Z])/g, ' $1').trim(),
            rarity: 'Common',
            description: '+4 Mult'
        };
    }
    if (type === 'tarot') {
        const found = SHOP_TAROTS.find(t => t.id === id);
        if (found) return found;
        return {
            id,
            title: id.replace(/([A-Z])/g, ' $1').trim(),
            rarity: 'Tarot',
            description: 'Enhance cards or generate resources'
        };
    }
    if (type === 'planet') {
        const found = SHOP_PLANETS.find(p => p.id === id);
        if (found) return found;
        return {
            id,
            title: id,
            rarity: 'Planet',
            description: `Level up ${id} poker hand`
        };
    }
    if (type === 'voucher') {
        const found = SHOP_VOUCHERS.find(v => v.id === id);
        if (found) return found;
        return {
            id,
            title: id.replace(/([A-Z])/g, ' $1').trim(),
            rarity: 'Voucher',
            description: 'Voucher effect'
        };
    }
    return {
        id,
        title: id,
        rarity: 'Common',
        description: ''
    };
}

